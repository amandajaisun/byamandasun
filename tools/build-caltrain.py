"""Builds caltrain.html (no password) from private/caltrain/content.html.

usage: python3 tools/build-caltrain.py

Images come from imgs/caltrain/. Each recording waits for a click before it
loads: it gets a poster frame (imgs/caltrain/<name>-poster.webp) and
preload="none", and site.js adds the play/pause control under it.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / 'private/caltrain/content.html').read_text()
src = re.sub(r'<!--.*?-->', '', src, flags=re.S).strip()
i = src.index('<style>')
body, style = src[:i].rstrip(), src[i:]


def video(m):
    label, name = m.group(1), m.group(2)
    return (f'<video aria-label="{label}" src="imgs/caltrain/{name}.mp4" '
            f'poster="imgs/caltrain/{name}-poster.webp" preload="none" loop muted playsinline></video>')


body = re.sub(r'<video aria-label="([^"]+)" data-src="media/([a-z-]+)\.mp4"[^>]*></video>', video, body)

# Everything after the first image waits until it's near the screen
first = True


def image(m):
    global first
    lazy = '' if first else ' loading="lazy"'
    first = False
    return f'<img{m.group(1)} src="imgs/caltrain/{m.group(2)}"{lazy}'


body = re.sub(r'<img([^>]*?) data-src="media/([^"]+)"', image, body)
assert 'data-src' not in body, 'media left without a source'

DESC = 'An iOS app that shows daily commuters their next Caltrain at a glance.'
SITE = 'https://byamandasun.com/'
page = f'''<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <!-- Generated by tools/build-caltrain.py from private/caltrain/content.html; edit that instead -->
    <title>Caltrain — amanda sun</title>
    <meta name="description" content="{DESC}">
    <link rel="canonical" href="{SITE}caltrain.html">
    <link rel="icon" href="favicon.svg" type="image/svg+xml">
    <link rel="apple-touch-icon" href="apple-touch-icon.png">
    <!-- Sharing preview -->
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="amanda sun">
    <meta property="og:title" content="Caltrain — Amanda Sun">
    <meta property="og:description" content="{DESC}">
    <meta property="og:url" content="{SITE}caltrain.html">
    <meta property="og:image" content="{SITE}imgs/share/caltrain.jpg">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta name="twitter:card" content="summary_large_image">
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=DM+Sans:ital,opsz,wght@0,9..40,100..1000;1,9..40,100..1000&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="styles.css">
    <link rel="stylesheet" href="project.css">
    <script src="site.js" defer></script>
    <script src="project.js" defer></script>
</head>
<body>
    <a class="skip-link" href="#main">skip to content</a>

    <!-- Navigation Pane -->
    <nav id="nav-pane" aria-label="pages">
        <a href="ux.html" class="nav-item active" data-key="2" aria-keyshortcuts="2">design</a>
        <a href="canvas.html" class="nav-item" data-key="3" aria-keyshortcuts="3">art</a>
        <a href="links.html" class="nav-item" data-key="4" aria-keyshortcuts="4">about</a>
    </nav>

    <!-- Signature -->
    <div id="signature"><a href="wind.html" class="nav-item" data-key="1" aria-label="amanda sun: home" aria-keyshortcuts="1">amanda sun</a></div>

    <main id="main" tabindex="-1">
{body}
    </main>

{style}
</body>
</html>
'''
(ROOT / 'caltrain.html').write_text(page)
print('wrote caltrain.html')
